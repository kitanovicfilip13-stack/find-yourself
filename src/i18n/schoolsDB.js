export function getTop5Schools(segment, city, scores) {
  const db = segment === 'srednja' ? srednjeSkole : fakulteti
  const cityData = db[city] || db['Beograd']

  // Sortiraj dimenzije po skoru
  const ranked = Object.entries(scores)
    .filter(([key]) => cityData[key])
    .sort((a, b) => b[1] - a[1])

  if (ranked.length === 0) return []

  const result = []

  // Uzmi top škole iz top 3 dimenzija, prioritet prvoj
  const weights = [3, 2, 1]
  ranked.slice(0, 3).forEach(([key], dimIdx) => {
    const schools = cityData[key] || []
    const count = weights[dimIdx] || 1
    schools.slice(0, count).forEach(school => {
      if (!result.includes(school)) result.push(school)
    })
  })

  // Dopuni do 5 ako treba
  ranked.forEach(([key]) => {
    if (result.length >= 5) return
    const schools = cityData[key] || []
    schools.forEach(school => {
      if (result.length < 5 && !result.includes(school)) result.push(school)
    })
  })

  return result.slice(0, 5)
}
